/** B114 independently verifies JSON output, not a world build. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {validateB114} from '../source/parallel/b114/main/compile-b114.mjs';
const r=JSON.parse(fs.readFileSync('b114-review-output/B114_Conditional_Circulation_15_Buildings.json','utf8'));
assert(validateB114(r));
assert.equal(r.readiness,'NOT_PREPARED');
assert.equal(r.constructionApproved,false);
assert.equal(r.executionAllowed,false);
assert.equal(r.worldContacts,0);
assert.equal(r.worldCoordinates,null);
assert.equal(r.commandCount,0);
assert.equal(r.BuildPlan.commandCount,0);
assert.equal(r.BuildPlan.worldCoordinates,null);
assert.deepEqual(r.BuildPlan.operations,[]);
assert.equal(r.gates.length,9);
assert(r.gates.every(g=>g.status==='BLOCKED'));
assert.equal(r.totals.educationValidatedStairStates,0);
assert.equal(r.totals.physicallyCertifiedFullBuildings,0);
assert.equal(r.totals.legacyUnapproved,296);
assert.equal(r.totals.legacyHeld,18);
assert(r.cases.every(c=>c.proposalsApplied===false&&c.physicalWholeBuildingWalkabilityCertified===false));
console.log('PASS B114: all proposed stair/gallery/furniture designs read-only; 9 construction gates BLOCKED');
