/**
 * R36: offline provenance-check wrapper for an independently authored R3
 * contract. This only checks claims and signatures; cannot authenticate humans,
 * dates, file capture, Git commits, or independence. Never calls a model/world.
 * An R3 contract is supplied, NEVER generated from model spatialPlan.
 */
import {createHash} from 'node:crypto';
import {readR4PlannedProposal}
 from '../source/ai/b198zr4-planned-source.mjs';
import {compareR35Independent}
 from './b198zr35-independent-contract-comparison-offline.mjs';
export const SCHEMA='minecraftaibuilder-b198zr36-independent-review-evidence-v1';
const hash=s=>createHash('sha256').update(s,'utf8').digest('hex');
const sha64=s=>typeof s==='string'&&/^[a-f0-9]{64}$/.test(s);
const commit40=s=>typeof s==='string'&&/^[a-f0-9]{40}$/.test(s);
const object=o=>o!==null&&typeof o==='object'&&!Array.isArray(o);
const exact=(o,keys)=>object(o)&&Object.keys(o).length===keys.length&&
 keys.every(k=>Object.hasOwn(o,k));
const safeText=(s,min=20,max=1000)=>typeof s==='string'&&
 s.trim().length>=min&&s.length<=max&&!/[\u0000-\u001f<>]/.test(s);
const utcTime=t=>typeof t==='string'&&
 /^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ$/.test(t)&&
 !Number.isNaN(Date.parse(t))&&new Date(t).toISOString()===
 t.slice(0,-1)+'.000Z';
const safety=()=>({readiness:'NOT_PREPARED',constructionApproved:false,
 executionAllowed:false,worldContacts:0,worldWrites:0,
 gates:Array(9).fill('BLOCKED'),BuildPlan:{operations:[]}});
function geometries(plan){
 // Exclude IDs, array order, and adjustable thresholds; renaming entries or
 // weakening counts cannot make a copied plan appear independently designed.
 const lists=(items,fields)=>items.map(v=>
  JSON.stringify(fields.map(k=>v[k]))).sort();
 return JSON.stringify({
  entrance:plan.entrance,headroom:plan.headroom,
  protectedVoids:lists(plan.protectedVoids,['origin','size']),
  destinations:lists(plan.destinations,['point']),
  functionalZones:lists(plan.functionalZones,['origin','size'])
 });
}
function rationalesValid(r,contract){
 if(!exact(r,['briefGrounding','entrance','protectedVoids','destinations',
  'functionalZones'])||
  !safeText(r.briefGrounding)||!safeText(r.entrance))return false;
 for(const [key,items] of [
  ['protectedVoids',contract.protectedVoids],
  ['destinations',contract.destinations],
  ['functionalZones',contract.functionalZones]]){
  const notes=r[key];
  if(!Array.isArray(items)||!Array.isArray(notes)||notes.length!==items.length)
   return false;
  const targetIds=items.map(x=>x.id).sort();
  const describedIds=notes.map(x=>x.id).sort();
  if(JSON.stringify(targetIds)!==JSON.stringify(describedIds))return false;
  if(notes.some(n=>!exact(n,['id','rationale'])||!safeText(n.rationale)))
   return false;
 }
 return true;
}
export function assessR36IndependentReview({
 candidateRaw=null,expectedSha256=null,independentContract=null,
 reviewerEvidence=null,expectedGitCommit=null,expectedBriefSha256=null,
 evidenceKind='USER_SUPPLIED_UNVERIFIED'
}={}){
 const core=compareR35Independent({candidateRaw,expectedSha256,
  independentContract,evidenceKind});
 const base={
  schema:SCHEMA,
  r35Status:core.status,
  candidateStrictB143:core.candidateStrictB143,
  candidateDeclaredR3:core.candidateDeclaredR3,
  candidateIndependentR3:core.candidateIndependentR3,
  candidateSha256:core.candidateSha256,
  independentAuthorshipAuthenticated:false,
  reviewerIdentityAuthenticated:false,
  reviewerTimestampExternallyVerified:false,
  gitCommitExternallyVerified:false,
  sourceBriefExternallyVerified:false,
  modelSpatialPlanCopiedDetected:null,
  reviewerEvidenceSignatureVerifiedAgainstSuppliedValues:false,
  rawOriginalFileVerified:false,
  humanArchitecturalQualityApproved:false,
  actualQwenPerformanceImprovement:'NOT_ESTABLISHED',
  contractAutoGenerated:false,contractAutoRepaired:false,
  modelCalls:0,worldContacts:0,worldWrites:0,
  constructionApproved:false,safety:safety()
 };
 if(core.status!=='INDEPENDENT_FORMAL_PASS_PROVENANCE_UNVERIFIED')
  return {...base,status:'HOLD_R35_NOT_ELIGIBLE'};
 const e=reviewerEvidence;
 if(!exact(e,['schema','reviewId','reviewerAlias','reviewedAtUtc',
  'gitCommit','briefSha256','candidateRawSha256',
  'independentContractSha256','independenceClaim',
  'modelSpatialPlanViewed','copiedFromModel','rationale'])||
  e.schema!==SCHEMA||
  typeof e.reviewId!=='string'||!/^[a-z][a-z0-9-]{2,47}$/.test(e.reviewId)||
  !safeText(e.reviewerAlias,3,80)||
  !utcTime(e.reviewedAtUtc)||
  !commit40(e.gitCommit)||!sha64(e.briefSha256)||
  !sha64(e.candidateRawSha256)||!sha64(e.independentContractSha256))
  return {...base,status:'HOLD_REVIEW_EVIDENCE_FIELDS'};
 if(!commit40(expectedGitCommit)||!sha64(expectedBriefSha256)||
  e.gitCommit!==expectedGitCommit||
  e.briefSha256!==expectedBriefSha256||
  e.candidateRawSha256!==core.candidateSha256||
  e.independentContractSha256!==hash(JSON.stringify(independentContract)))
  return {...base,status:'HOLD_REVIEW_EVIDENCE_HASH_OR_COMMIT_MISMATCH'};
 if(e.independenceClaim!==true||e.modelSpatialPlanViewed!==false||
  e.copiedFromModel!==false)
  return {...base,status:'HOLD_REVIEWER_INDEPENDENCE_NOT_CLAIMED'};
 if(!rationalesValid(e.rationale,independentContract))
  return {...base,status:'HOLD_REVIEW_RATIONALE_INCOMPLETE'};
 // Model spatialPlan is inspected ONLY to detect duplication, NEVER to
 // construct the independent contract or replace the supplied reviewer notes.
 const proposal=readR4PlannedProposal(candidateRaw);
 const copied=geometries(independentContract)===geometries(proposal.spatialPlan);
 if(copied)return {...base,status:'HOLD_MODEL_PLAN_GEOMETRY_DUPLICATED',
  modelSpatialPlanCopiedDetected:true};
 return {...base,
  status:'REVIEWER_EVIDENCE_CONSISTENCY_PASS_AUTHORSHIP_UNVERIFIED',
  modelSpatialPlanCopiedDetected:false,
  reviewerEvidenceSignatureVerifiedAgainstSuppliedValues:true,
  reviewId:e.reviewId,declaredReviewerAlias:e.reviewerAlias,
  declaredReviewedAtUtc:e.reviewedAtUtc,
  declaredGitCommit:e.gitCommit,
  declaredBriefSha256:e.briefSha256,
  suppliedIndependentContractSha256:e.independentContractSha256,
  reviewerClaimIsSelfReported:true,
  provenanceAuthenticated:false,
  independentResults:core.independentResults
 };
}
