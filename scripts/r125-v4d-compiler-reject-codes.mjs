export const safeStaticCompilerRejectCode=x=>
 typeof x==='string'&&allowed.has(x)?x:UNKNOWN_COMPILER_REJECT;
export function classifyPrivateCompilerRejection(errorMessage){
 if(typeof errorMessage!=='string'||errorMessage.length>240)
  return UNKNOWN_COMPILER_REJECT;
 if(exact.has(errorMessage))return exact.get(errorMessage);
 for(const [pattern,code] of indexed)
  if(pattern.test(errorMessage))return code;
 return UNKNOWN_COMPILER_REJECT;
}
