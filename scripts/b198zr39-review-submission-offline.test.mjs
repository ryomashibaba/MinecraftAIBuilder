  submitR39Review({submitted:entry(),directory:output(root)});
  const r=diagnoseR39Bundle({directory:output(root)});
  assert.equal(r.status,'BUNDLE_STRUCTURE_AND_SUPPLIED_PINS_CHECKED_NOT_AUTHENTICATED');
  assert.equal(r.diagnosticCode,'SELF_CONSISTENT_UNANCHORED');
  assert.equal(r.externalPinAuthenticated,false);
  assert.equal(r.qualityApprovalGranted,false);
