/**
 * R35: strictly offline candidate vs independent R3 review.
 * Authorship strings are CLAIMS; this function cannot authenticate a human.
 * Independent contract must already exist; never generate/repair/repin it.
 */
import {createHash} from 'node:crypto';
import {readR4PlannedProposal,reviewR4PlannedProposal}
 from '../source/ai/b198zr4-planned-source.mjs';
import {compileDesign} from '../source/ai/b143-building-dsl.mjs';
import {SCHEMA as R3_SCHEMA,evaluateFunctionalReviewContract}
 from '../source/ai/b198zr3-functional-review-contract.mjs';
import {compareR34Evidence}
 from './b198zr34-fair-evidence-comparison-offline.mjs';
export const SCHEMA='minecraftaibuilder-b198zr35-independent-contract-comparison-v1';
const hash=s=>createHash('sha256').update(s,'utf8').digest('hex');
const sha64=/^[a-f0-9]{64}$/;
const safety=()=>({readiness:'NOT_PREPARED',constructionApproved:false,
 executionAllowed:false,worldContacts:0,worldWrites:0,
 gates:Array(9).fill('BLOCKED'),BuildPlan:{operations:[]}});
const reason=e=>{
 const s=String(e?.message||e);
 return s.match(/^(B198ZR3_CONTRACT_[A-Z0-9_]+|B198ZR4_[A-Z0-9_]+|B143_[A-Z0-9_]+)/)?.[1]||
  'STRICT_REVIEW_REJECTED';
};
export function compareR35Independent({
 candidateRaw=null,expectedSha256=null,independentContract=null,
 evidenceKind='USER_SUPPLIED_UNVERIFIED'
}={}){
 const base=compareR34Evidence({candidateRaw,expectedSha256,evidenceKind});
 const output={
  schema:SCHEMA,r34Status:base.status,
  candidateSha256:base.candidateSha256??null,
  candidateStrictB143:base.candidateStrictB143,
  candidateDeclaredR3:base.candidateDeclaredR3,
  candidateIndependentR3:'NOT_EVALUATED',
  claimedContractAuthorship:independentContract?.authorship??null,
  independentAuthorshipAuthenticated:false,
  contractSourceSha256:independentContract?.sourceSha256??null,
  contractAutoGenerated:false,contractAutoRepaired:false,
  contractAutoRepinned:false,
  modelOriginAuthenticated:false,
  humanArchitecturalQualityApproved:false,
  actualQwenPerformanceImprovement:'NOT_ESTABLISHED',
  r25OriginalStatus:'HOLD',
  modelCalls:0,worldContacts:0,worldWrites:0,
  safety:safety()
 };
 if(!independentContract)return {...output,status:
  'NO_INDEPENDENT_CONTRACT',candidateIndependentR3:'NOT_EVALUATED_MISSING_CONTRACT'};
 if(base.status!=='CANDIDATE_FORMAL_DECLARED_PASS_NOT_INDEPENDENT')
  return {...output,status:'HOLD_CANDIDATE_NOT_FORMALLY_ELIGIBLE'};
 if(!independentContract||typeof independentContract!=='object'||
  Array.isArray(independentContract)||
  independentContract.schema!==R3_SCHEMA||
  !['INDEPENDENT_REVIEW_DRAFT','TEST_FIXTURE'].includes(independentContract.authorship))
  return {...output,status:'HOLD_UNTRUSTED_CONTRACT_AUTHORSHIP_OR_SCHEMA'};
 if(!sha64.test(independentContract.sourceSha256??''))
  return {...output,status:'HOLD_CONTRACT_SOURCE_PIN_INVALID'};
 // Source is parsed only after R34 has checked caller-supplied text SHA.
 // No Qwen or Minecraft code is imported or called.
 try{
  const proposal=readR4PlannedProposal(candidateRaw);
  const compiled=compileDesign(proposal.design);
  if(independentContract.sourceSha256!==compiled.sourceSha256)
   return {...output,status:'HOLD_INDEPENDENT_SOURCE_SHA_STALE',
    candidateCompiledSourceSha256:compiled.sourceSha256};
  const independent=evaluateFunctionalReviewContract({
   design:proposal.design,compiled,contract:independentContract});
  const passed=independent.status==='FORMAL_GEOMETRY_AND_ROUTE_CONSTRAINTS_PASS';
  return {...output,status:passed?
    'INDEPENDENT_FORMAL_PASS_PROVENANCE_UNVERIFIED':
    'HOLD_INDEPENDENT_FUNCTIONAL_CONTRACT',
   candidateCompiledSourceSha256:compiled.sourceSha256,
   candidateIndependentR3:independent.status,
   independentResults:{
    protectedVoids:independent.results.protectedVoids,
    destinations:independent.results.destinations,
    functionalZones:independent.results.functionalZones,
    abstractReachablePositions:independent.results.abstractReachablePositions
   },
   claimedContractAuthorship:independent.contractAuthorship,
   independentAuthorshipAuthenticated:false
  };
 }catch(e){
  return {...output,status:'HOLD_INDEPENDENT_CONTRACT_REJECTED',
   rejectionCode:reason(e),candidateIndependentR3:'REJECTED'};
 }
}
