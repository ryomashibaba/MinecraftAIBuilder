import assert from 'node:assert/strict';
import fs from 'node:fs';
import { compileB100, validateB100 } from '../source/parallel/b100/main/compile-b100.mjs';
const p='source/parallel/b100/main/B100_GENERIC_DESIGN_REPORT.json';
const frozen=JSON.parse(fs.readFileSync(p,'utf8'));
const generated=compileB100();
assert.deepEqual(generated,frozen,'B100 pinned baseline must remain reproducible');
assert.equal(validateB100(generated),true);
assert.equal(generated.targetEdition,'MINECRAFT_EDUCATION');
assert.equal(generated.readiness,'NOT_PREPARED');
assert.equal(generated.executionAllowed,false);
assert.equal(generated.constructionApproved,false);
assert.equal(generated.worldContacts,0);
assert.equal(generated.BuildPlan.operations.length,0);
assert.equal(generated.BuildPlan.commandCount,0);
assert.equal(generated.BuildPlan.worldCoordinates,null);
assert.equal(generated.gates.length,9);
assert(generated.gates.every(g=>g.status==='BLOCKED'));
assert.equal(generated.totals.previousUnapprovedRooms,296);
assert.equal(generated.totals.previousHeldRooms,18);
assert.equal(generated.totals.newApprovedRooms,0);
assert.equal(generated.editionAdapter.worldTransportStatus,'DISABLED');
assert.equal(generated.editionAdapter.futureJavaAdapter,'FUTURE_SEPARATE_BACKEND_NOT_IMPLEMENTED');
console.log('PASS: B100 reproducible; Education-only; no commands; frozen 296+18; 9 gates blocked');
