#!/usr/bin/env python3
"""Strict public GitHub research handoff for two PRIVATE Qwen source drafts.

Public means PUBLIC FOREVER in Git history; not a privacy/encryption feature.
One immutable pinned source, one selected project, two UTF-8 source snapshots.
No arbitrary shell arguments, paths, test commands, credentials or tokens.
Cannot prove source was generated by a model, only validate its provenance
claims and safely constrain its structure before Docker QA.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re

from draft_real_project_local14b import ANCHORS
from prepare_pinned_real_project import load_manifest
from promote_private_real_drafts_docker import _check_one_contiguous_revision

SCHEMA = "dec-public-research-source-qa-handoff-v1"
PRIVACY_ACK = "I_ACCEPT_PUBLIC_GIT_HISTORY_FOR_THESE_TWO_SOURCE_DRAFTS"
SUBDIR = "tools/free-autonomy-solo/submissions"
ALLOWED_MODEL = re.compile(r"[A-Za-z0-9_.:/-]{1,100}\Z")
SHA40 = re.compile(r"[a-f0-9]{40}\Z")
SHA256 = re.compile(r"[a-f0-9]{64}\Z")
FILENAME = re.compile(r"tools/free-autonomy-solo/submissions/[a-f0-9]{32}\.json\Z")
KEYS = {
    "schema", "project", "source_commit", "source_blob_sha",
    "source_before_sha256", "model_reported_only",
    "stage1_source", "stage2_source",
    "stage1_sha256", "stage2_sha256",
    "privacy_ack", "synthetic_fixture",
}
# Conservative best-effort guard. Not a proof that drafts contain no secrets.
SECRET_RE = re.compile(
    r"-----BEGIN (?:RSA |EC |OPENSSH |DSA )?PRIVATE KEY-----"
    r"|(?i:gh[pousr]_[a-z0-9]{15,})"
    r"|(?i:github_pat_[a-z0-9_]{15,})"
    r"|(?i:sk-[a-z0-9_-]{18,})"
    r"|(?i:AKIA[0-9A-Z]{16})"
    r"|(?i:(?:api[_-]?key|authorization|access[_-]?token)\s*[:=]\s*['\"]?[a-z0-9_-]{16,})"
)


class Hold(RuntimeError):
    pass


def sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def assert_public_drafts_safe(previous: str, first: str, second: str,
                              project: str) -> None:
    for before, after in ((previous, first), (first, second)):
        try:
            _check_one_contiguous_revision(before, after)
        except Exception as exc:
            raise Hold("DRAFT_SCOPE_NOT_APPROVED") from exc
        if len(after.encode("utf-8")) > 16000 or "\x00" in after:
            raise Hold("SOURCE_SIZE_OR_NUL_NOT_ALLOWED")
        for anchor in ANCHORS[project]:
            if before.count(anchor) and after.count(anchor) < before.count(anchor):
                raise Hold("SOURCE_PROTECTED_API_REMOVED")
        if SECRET_RE.search(after):
            raise Hold("POSSIBLE_SECRET_IN_PUBLIC_DRAFT")
    if first == second or first == previous:
        raise Hold("PUBLIC_DRAFT_STAGE_NOOP")


def validate_payload(payload: dict, original: str, *,
                     manifest: dict | None = None) -> dict:
    manifest = load_manifest() if manifest is None else manifest
    if not isinstance(payload, dict) or set(payload) != KEYS:
        raise Hold("PUBLIC_SUBMISSION_SCHEMA_FIELDS_INVALID")
    if payload.get("schema") != SCHEMA or payload.get("privacy_ack") != PRIVACY_ACK:
        raise Hold("PUBLIC_SUBMISSION_NOT_EXPLICITLY_APPROVED")
    if type(payload["synthetic_fixture"]) is not bool:
        raise Hold("SYNTHETIC_FIELD_NOT_BOOLEAN")
    project = payload["project"]
    if project not in {"minecraftaibuilder", "browser-ink-tps"}:
        raise Hold("PROJECT_NOT_APPROVED")
    lane = manifest["project_candidates"][project]
    if payload["source_commit"] != lane["pinned_commit"]:
        raise Hold("PINNED_COMMIT_MISMATCH")
    if payload["source_blob_sha"] != lane["source_blob_sha"]:
        raise Hold("PINNED_BLOB_MISMATCH")
    if not isinstance(payload["model_reported_only"], str) or not ALLOWED_MODEL.fullmatch(payload["model_reported_only"]):
        raise Hold("MODEL_LABEL_INVALID")
    for key in ("source_before_sha256", "stage1_sha256", "stage2_sha256"):
        if not isinstance(payload[key], str) or not SHA256.fullmatch(payload[key]):
            raise Hold("SOURCE_HASH_INVALID")
    if not isinstance(original, str) or len(original.encode("utf-8")) > 16000:
        raise Hold("BASELINE_SIZE_INVALID")
    a, b = payload["stage1_source"], payload["stage2_source"]
    if not isinstance(a, str) or not isinstance(b, str):
        raise Hold("SOURCE_NOT_UTF8_STRING")
    if (payload["source_before_sha256"] != sha(original)
            or payload["stage1_sha256"] != sha(a)
            or payload["stage2_sha256"] != sha(b)):
        raise Hold("SOURCE_HASH_CHAIN_MISMATCH")
    assert_public_drafts_safe(original, a, b, project)
    return {
        "project": project, "source_commit": lane["pinned_commit"],
        "source_file": lane["source_file"], "model_reported_only": payload["model_reported_only"],
        "synthetic_fixture": payload["synthetic_fixture"],
        "stage_hashes_verified": True,
    }


def read_submission(path: Path) -> dict:
    if path.is_symlink() or not path.is_file() or path.stat().st_size > 42000:
        raise Hold("PUBLIC_SUBMISSION_FILE_INVALID")
    raw = path.read_bytes()
    try:
        data = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, ValueError) as exc:
        raise Hold("PUBLIC_SUBMISSION_INVALID_JSON") from exc
    if not isinstance(data, dict):
        raise Hold("PUBLIC_SUBMISSION_NOT_OBJECT")
    return data


def make_payload(project: str, model: str, original: str, first: str,
                 second: str, *, synthetic: bool, manifest: dict | None = None) -> dict:
    manifest = load_manifest() if manifest is None else manifest
    if project not in manifest["project_candidates"]:
        raise Hold("PROJECT_NOT_APPROVED")
    lane = manifest["project_candidates"][project]
    payload = {
        "schema": SCHEMA, "project": project,
        "source_commit": lane["pinned_commit"],
        "source_blob_sha": lane["source_blob_sha"],
        "source_before_sha256": sha(original),
        "model_reported_only": model,
        "stage1_source": first, "stage2_source": second,
        "stage1_sha256": sha(first), "stage2_sha256": sha(second),
        "privacy_ack": PRIVACY_ACK, "synthetic_fixture": synthetic,
    }
    validate_payload(payload, original, manifest=manifest)
    return payload


def safe_submission_path(relpath: str) -> str:
    if not isinstance(relpath, str) or not FILENAME.fullmatch(relpath):
        raise Hold("PUBLIC_SUBMISSION_PATH_NOT_ALLOWED")
    return relpath
