#!/usr/bin/env python3
"""One real Qwen3:4b cycle in the NEW MAB cumulative SOURCE pipeline.

Ephemeral public GitHub CI ONLY. Source generated by genuine Ollama model,
verified by actual isolated Docker QA. No project main, GitHub push, world
write, generated host-code execution or publication of private model output.
This never tests user's Windows Qwen3:14b or multi-cycle success.
"""
from __future__ import annotations
import json
import os
from pathlib import Path
import subprocess
import tempfile

from real_small_model_ci_once import MODEL, IMAGE, cmd, wait_ready
from run_mab_private_continuous import PASS, run_cumulative


def experiment() -> dict:
    report = {
        "schema": "dec-real-qwen4b-cumulative-source-one-v1",
        "status": "HOLD",
        "model_requested": MODEL,
        "model_calls_attempted": 0,
        "genuine_ollama_started": False,
        "qa_verified_stages": 0,
        "private_review_stages": 0,
        "completed_cycles": 0,
        "real_docker_qa_verified": False,
        "private_git_source_chain_verified": False,
        "user_windows_accessed": False,
        "real_qwen14b_executed": False,
        "art_or_minecraft_certified": False,
        "github_pushes": 0, "paid_api_calls": 0,
        "source_or_world_writes": 0,
    }
    with tempfile.TemporaryDirectory(prefix="dec-real-qwen4b-chain-") as tmp:
        root = Path(tmp)
        os.environ["LOCALAPPDATA"] = str(root / "lock")
        (root / "lock").mkdir()
        container = "dec-qwen4b-cumulative-" + str(os.getpid())
        try:
            cmd(["docker", "run", "-d", "--rm", "--name", container,
                 "--cap-drop=ALL", "--security-opt=no-new-privileges",
                 "--pids-limit", "128", "--memory", "5g", "--cpus", "3",
                 "-p", "127.0.0.1:11434:11434", IMAGE], timeout=55)
            wait_ready()
            cmd(["docker", "exec", container, "ollama", "pull", MODEL],
                timeout=450)
            wait_ready()
            report["genuine_ollama_started"] = True
            source, private_path = run_cumulative(
                model=MODEL, cycles=1,
                private_root=root / "ephemeral-private")
            # The report contains no source or local paths. The private source
            # and the actual QA Git commits die with this temp directory.
            report["model_calls_attempted"] = source.get("model_calls_attempted", 0)
            report["completed_cycles"] = source.get("completed_cycles", 0)
            report["qa_verified_stages"] = source.get("completed_qa_source_stages", 0)
            report["private_review_stages"] = source.get("private_review_stages", 0)
            report["original_source_sha"] = source.get("base_audited_public_source_commit")
            report["source_status"] = source.get("status")
            if source.get("reason_code"):
                report["reason_code"] = source["reason_code"]
            if (source.get("status") == PASS
                    and report["completed_cycles"] == 1
                    and report["qa_verified_stages"] == 2
                    and report["private_review_stages"] == 2
                    and report["model_calls_attempted"] >= 2
                    and len(source.get("accepted_cycles", [])) == 1
                    and source.get("github_pushes") == 0):
                report["status"] = "GENUINE_QWEN4B_SINGLE_CUMULATIVE_SOURCE_QA_ONLY"
                report["real_docker_qa_verified"] = True
                report["private_git_source_chain_verified"] = True
            else:
                report["status"] = "HOLD_GENUINE_CUMULATIVE_SOURCE_QA"
        except Exception as exc:
            report["status"] = "HOLD_GENUINE_INFRASTRUCTURE"
            report["exception_class"] = type(exc).__name__
        finally:
            subprocess.run(["docker", "rm", "-f", container],
                           capture_output=True, timeout=25, check=False)
    return report


def main() -> int:
    result = experiment()
    print(json.dumps(result, sort_keys=True, indent=2, ensure_ascii=False))
    temp = os.environ.get("RUNNER_TEMP")
    if temp:
        (Path(temp) / "dec-qwen4b-cumulative-sanitized.json").write_text(
            json.dumps(result, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    return 0 if result["status"].startswith("GENUINE_QWEN4B_SINGLE") else 2


if __name__ == "__main__":
    raise SystemExit(main())
